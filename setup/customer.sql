DROP TABLE IF EXISTS customer CASCADE;

CREATE TABLE customer  (
    id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    first_name TEXT,
    last_name TEXT,
    address_id INTEGER REFERENCES address(id),
    since DATE,
    phone_numbers JSONB,
    email_addresses JSONB,
    social_media JSONB
);    

TRUNCATE customer CASCADE;
