-- a simple trigger to demonstrate the concept and illustrate the trigger-specific variables

CREATE OR REPLACE FUNCTION trf_product_change () RETURNS TRIGGER 
AS 
$$
    BEGIN
    RAISE NOTICE 'Trigger name % called % at level % for operation %',
        TG_NAME, TG_WHEN, TG_LEVEL, TG_OP;
    RAISE NOTICE 'Price changed from % to % for product % ', OLD.price, NEW.price, OLD.product_nbr;
    RAISE NOTICE 'Old record %', OLD;
    RAISE NOTICE 'New record %', NEW;

    RETURN NEW;
    END;
$$ LANGUAGE PLPGSQL;

CREATE OR REPLACE TRIGGER tr_product_change
    BEFORE INSERT OR UPDATE 
    ON product
FOR EACH ROW EXECUTE FUNCTION trf_product_change();

-- try it out

INSERT INTO product (product_nbr, category_id, name, price) 
    VALUES 
        ('new_cheese', 5, 'Cheese 10% fat', 19.00);

UPDATE product SET price = 20.00 WHERE product_nbr = 'new_cheese';        

DELETE FROM product WHERE product_nbr = 'new_cheese';

-- create a trigger that fires on DELETE

CREATE OR REPLACE FUNCTION trf_product_delete () RETURNS TRIGGER
AS
$$
    BEGIN
    RAISE NOTICE 'Deleting product % with the following info %',
        OLD.product_nbr, OLD;
    -- OLD needs to be returned, as NEW is not defined in delete
    RETURN OLD;
    END;
$$ LANGUAGE PLPGSQL;

CREATE OR REPLACE TRIGGER tr_product_delete 
    BEFORE DELETE
    ON product
FOR EACH ROW EXECUTE FUNCTION trf_product_delete ();

