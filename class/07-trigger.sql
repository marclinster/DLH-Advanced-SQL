-- define a function that rounds the price and writes a message
CREATE OR REPLACE FUNCTION trf_product_price_round () RETURNS TRIGGER 
AS 
$$
    DECLARE v_original_price NUMERIC(10,2);
    BEGIN
        v_original_price = NEW.price;
        NEW.price = ROUND (v_original_price);
        RAISE NOTICE 'Price changed from % to % for product % after rounding from %', 
            OLD.price, NEW.price, NEW.product_nbr, v_original_price;
    RETURN NEW;
    END;
$$ LANGUAGE PLPGSQL;

-- add it as a trigger that fires on update of the price 
CREATE OR REPLACE TRIGGER tr_product_price_round
    BEFORE UPDATE OF price
    ON product
FOR EACH ROW EXECUTE FUNCTION trf_product_price_round();

